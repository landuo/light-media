var ownedCommandLargeSourceRaw []byte

type ownedCommandLargeSource struct {
	Payload struct {
		ID     string
		Bytes  int
		SHA256 string
		Recipe struct {
			Prefix string `json:"prefix_base64"`
			Repeat string `json:"repeat_ascii"`
			Count  int    `json:"repeat_count"`
			Suffix string `json:"suffix_base64"`
		}
	}
	Cases []struct {
		ID      string
		Outcome struct {
			Kind  string
			Value json.RawMessage
		}
		Trace []struct {
			Op     string
			Kwargs json.RawMessage
		}
	}
}

func ownedCommandLargeOracle(t *testing.T) ownedCommandLargeSource {
	t.Helper()
	// Fixed entire actual original output; no expected values are generated by Go.
	sum := sha256.Sum256(ownedCommandLargeSourceRaw)
	if hex.EncodeToString(sum[:]) != "e03f9261b59b8bcd47b82aa437be20c1f95784a10648baff46293743405cce1d" {
		t.Fatal("original large material raw drift")
	}
	var source ownedCommandLargeSource
	if json.Unmarshal(ownedCommandLargeSourceRaw, &source) != nil || source.Payload.ID != "valid_large_padding" || source.Payload.Bytes != 16777378 || source.Payload.SHA256 != "24a8cca8ab9e597b0672f2bfeca9be4e97bca649e1f07089d237c6681c417ba5" {
		t.Fatal("original input observation missing")
	}
	prefix, err := base64.StdEncoding.Strict().DecodeString(source.Payload.Recipe.Prefix)
	if err != nil {
		t.Fatal(err)
	}
	suffix, err := base64.StdEncoding.Strict().DecodeString(source.Payload.Recipe.Suffix)
	if err != nil || source.Payload.Recipe.Repeat != "x" || source.Payload.Recipe.Count != 16777217 {
		t.Fatal("original recipe differs")
	}
	h := sha256.New()
	_, _ = h.Write(prefix)
	block := bytes.Repeat([]byte("x"), 64<<10)
	for remaining := source.Payload.Recipe.Count; remaining > 0; {
		n := min(remaining, len(block))
		_, _ = h.Write(block[:n])
		remaining -= n
	}
	_, _ = h.Write(suffix)
	if len(prefix)+source.Payload.Recipe.Count+len(suffix) != source.Payload.Bytes || hex.EncodeToString(h.Sum(nil)) != source.Payload.SHA256 {
		t.Fatal("original recipe length/hash differs")
	}
	return source
}
func (s ownedCommandLargeSource) value(t *testing.T, id string) json.RawMessage {
	t.Helper()
	for _, c := range s.Cases {
		if c.ID == id {
			if c.Outcome.Kind != "return" {
				t.Fatal("original did not return", id)
			}
			return bytes.Clone(c.Outcome.Value)
		}
	}
	t.Fatal("missing original case", id)
	return nil
}
func (s ownedCommandLargeSource) args(t *testing.T, kind string) map[string]any {
	t.Helper()
	id := "s03_qb_bytes"
	if kind == "transmission" {
		id = "s03_tr_bytes"
	}
	for _, c := range s.Cases {
		if c.ID == id {
			if len(c.Trace) != 1 {
				t.Fatal("unexpected original add trace")
			}
			var args map[string]any
			d := json.NewDecoder(bytes.NewReader(c.Trace[0].Kwargs))
			d.UseNumber()
			if d.Decode(&args) != nil {
				t.Fatal("invalid original args")
			}
			return args
		}
	}
	t.Fatal("missing original args")
	return nil
}
func ownedCommandSourceOperation(t *testing.T, source ownedCommandLargeSource, kind string) map[string]any {
	t.Helper()
	original := source.args(t, kind)
	// Only this explicit source argument projection; no endpoint/credentials.
	args := map[string]any{"download_dir": original["save_path"], "is_paused": original["is_paused"], "tag": original["tags"]}
	id := ownedCommandQBID
	if kind == "transmission" {
		id = ownedCommandTRID
		args = map[string]any{"download_dir": original["download_dir"], "is_paused": original["paused"], "labels": original["labels"]}
	}
	return map[string]any{"kind": kind, "op": "add", "downloader_id": id, "args": args, "source_material": source.Payload.ID}
}

type ownedMaterialNativeObservation struct {
	Requests         int
	Unexpected       int
	QB, TR           int
	Failed           int
	QBBytes, TRBytes int64
	QBSHA, TRSHA     string
}
type ownedMaterialNativePeers struct {
	mu          sync.Mutex
	qb, tr      *httptest.Server
	source      ownedCommandLargeSource
	trReply     []byte
	observation ownedMaterialNativeObservation
	failTR      bool
}

func (p *ownedMaterialNativePeers) snapshot() ownedMaterialNativeObservation {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.observation
}
func (p *ownedMaterialNativePeers) reject(w http.ResponseWriter) {
	p.observation.Unexpected++
	http.Error(w, "unexpected owned material request", 400)
}
func newOwnedMaterialNativePeers(t *testing.T, source ownedCommandLargeSource) *ownedMaterialNativePeers {
	t.Helper()
	// The original collector's recording reply is not a complete real daemon
	// envelope. Add only the required owned protocol id, never call it oracle.
	var reply map[string]json.RawMessage
	if json.Unmarshal(source.value(t, "s03_tr_bytes"), &reply) != nil || reply == nil || reply["id"] != nil {
		t.Fatal("original recording reply projection changed")
	}
	reply["id"] = json.RawMessage(`901`)
	encoded, err := json.Marshal(reply)
	if err != nil {
		t.Fatal(err)
	}
	p := &ownedMaterialNativePeers{source: source, trReply: encoded}
	p.qb = ownedCommandTCP4Peer(t, http.HandlerFunc(p.qbHandler))
	p.tr = ownedCommandTCP4Peer(t, http.HandlerFunc(p.trHandler))
	t.Cleanup(func() {
		p.qb.Close()
		p.tr.Close()
		if p.snapshot().Unexpected != 0 {
			t.Error("unexpected fixed native request")
		}
	})
	return p
}
func (p *ownedMaterialNativePeers) qbHandler(w http.ResponseWriter, r *http.Request) {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.observation.Requests++
	r.Body = http.MaxBytesReader(w, r.Body, 24<<20)
	if r.URL.RawQuery != "" {
		p.reject(w)
		return
	}
	if r.URL.Path == "/api/v2/auth/login" {
		if r.Method != "POST" || r.ParseForm() != nil || len(r.PostForm) != 2 || r.PostForm.Get("username") != ownedCommandUsername || r.PostForm.Get("password") != ownedCommandPassword {
			p.reject(w)
			return
		}
		http.SetCookie(w, &http.Cookie{Name: "SID", Value: ownedCommandSession, Path: "/"})
		_, _ = io.WriteString(w, "Ok.")
		return
	}
	cookie, err := r.Cookie("SID")
	if err != nil || cookie.Value != ownedCommandSession {
		p.reject(w)
		return
	}
	if r.URL.Path == "/api/v2/app/webapiVersion" {
		if r.Method != "GET" {
			p.reject(w)
			return
		}
		_, _ = io.WriteString(w, "2.14.0")
		return
	}
	if r.Method != "POST" || r.URL.Path != "/api/v2/torrents/add" || r.ContentLength <= int64(p.source.Payload.Bytes) {
		p.reject(w)
		return
	}
	mr, err := r.MultipartReader()
	if err != nil {
		p.reject(w)
		return
	}
	fields := map[string]string{}
	files := 0
	var size int64
	var digest string
	for {
		part, err := mr.NextPart()
		if err == io.EOF {
			break
		}
		if err != nil {
			p.reject(w)
			return
		}
		if part.FileName() != "" {
			files++
			if part.FormName() != "torrent__0" || part.FileName() != "torrent__0" || part.Header.Get("Content-Type") != "" {
				part.Close()
				p.reject(w)
				return
			}
			h := sha256.New()
			size, err = io.Copy(h, io.LimitReader(part, int64(p.source.Payload.Bytes)+1))
			digest = hex.EncodeToString(h.Sum(nil))
			if err != nil || size != int64(p.source.Payload.Bytes) || digest != p.source.Payload.SHA256 {
				part.Close()
				p.reject(w)
				return
			}
		} else {
			v, err := io.ReadAll(io.LimitReader(part, 4097))
			_, exists := fields[part.FormName()]
			if err != nil || len(v) > 4096 || exists {
				part.Close()
				p.reject(w)
				return
			}
			fields[part.FormName()] = string(v)
		}
		if part.Close() != nil {
			p.reject(w)
			return
		}
	}
	want := map[string]string{"savepath": "/owned/save", "paused": "True", "stopped": "True", "tags": "owned", "autoTMM": "False", "sequentialDownload": "False", "firstLastPiecePrio": "False"}
	if files != 1 || !reflect.DeepEqual(fields, want) {
		p.reject(w)
		return
	}
	p.observation.QB++
	p.observation.QBBytes = size
	p.observation.QBSHA = digest
	_, _ = io.WriteString(w, "Ok.") // source actual recording response semantics: (True,[])
}
func (p *ownedMaterialNativePeers) trHandler(w http.ResponseWriter, r *http.Request) {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.observation.Requests++
	r.Body = http.MaxBytesReader(w, r.Body, 24<<20)
	user, password, ok := r.BasicAuth()
	if r.Method != "POST" || r.URL.Path != "/transmission/rpc" || r.URL.RawQuery != "" || !ok || user != ownedCommandUsername || password != ownedCommandPassword {
		p.reject(w)
		return
	}
	var call struct {
		Method    string         `json:"method"`
		Arguments map[string]any `json:"arguments"`
	}
	decoder := json.NewDecoder(r.Body)
	decoder.UseNumber()
	decoder.DisallowUnknownFields()
	if decoder.Decode(&call) != nil || decoder.Decode(new(any)) != io.EOF || call.Arguments == nil {
		p.reject(w)
		return
	}
	if r.Header.Get("X-Transmission-Session-Id") != ownedCommandSession {
		if call.Method != "session-get" || len(call.Arguments) != 0 {
			p.reject(w)
			return
		}
		w.Header().Set("X-Transmission-Session-Id", ownedCommandSession)
		w.WriteHeader(409)
		return
	}
	if call.Method == "session-get" {
		if len(call.Arguments) != 0 {
			p.reject(w)
			return
		}
		_, _ = io.WriteString(w, `{"result":"success","arguments":{"rpc-version":17}}`)
		return
	}
	if call.Method != "torrent-add" || r.ContentLength <= int64(p.source.Payload.Bytes) {
		p.reject(w)
		return
	}
	encoded, ok := call.Arguments["metainfo"].(string)
	if !ok {
		p.reject(w)
		return
	}
	delete(call.Arguments, "metainfo")
	want := map[string]any{"download-dir": "/owned/save", "paused": true, "labels": []any{"owned"}}
	if !reflect.DeepEqual(call.Arguments, want) {
		p.reject(w)
		return
	}
	h := sha256.New()
	size, err := io.Copy(h, base64.NewDecoder(base64.StdEncoding.Strict(), strings.NewReader(encoded)))
	digest := hex.EncodeToString(h.Sum(nil))
	if err != nil || size != int64(p.source.Payload.Bytes) || digest != p.source.Payload.SHA256 {
		p.reject(w)
		return
	}
	p.observation.TR++
	p.observation.TRBytes = size
	p.observation.TRSHA = digest
	if p.failTR {
		p.failTR = false
		p.observation.Failed++
		http.Error(w, "owned selected failure", 500)
		return
	}
	_, _ = w.Write(append(append([]byte(`{"result":"success","arguments":{"torrent-added":`), p.trReply...), []byte(`}}`)...))
}

type ownedMaterialGrantSummary struct {
	Contract, Capability, Direction, Kind, SHA256 string
	Total                                         int64
	ChunkBytes                                    int `json:"chunk_bytes"`
}
type ownedMaterialWorkerSummary struct {
	ownedCommandWorkerResult
	Grants         []*ownedMaterialGrantSummary
	MaterialBegins []int
}

func ownedMaterialWorkerQuery(t *testing.T, a *App, cookie *http.Cookie, probe bool, operations ...map[string]any) ownedMaterialWorkerSummary {
	t.Helper()
	response := callTest(t, a.Handler(), "POST", "/api/v1/plugin/"+ownedCommandWorkerID+"/commands", string(ownedCommandWorkerInput(t, probe, operations...)), cookie, "")
	if response.Code != 200 {
		t.Fatalf("actual owned material API HTTP %d", response.Code)
	}
	result := ownedMaterialWorkerSummary{ownedCommandWorkerResult: ownedCommandWorkerDecode(t, response.Body.Bytes(), len(operations))}
	var metadata struct {
		Results []struct {
			Grant     *ownedMaterialGrantSummary `json:"material_grant"`
			HostCalls struct {
				MaterialBegin int `json:"material_begin"`
			} `json:"host_calls"`
		}
	}
	if json.Unmarshal(response.Body.Bytes(), &metadata) != nil || len(metadata.Results) != len(result.Results) {
		t.Fatal("actual grant observation absent")
	}
	for _, v := range metadata.Results {
		result.Grants = append(result.Grants, v.Grant)
		result.MaterialBegins = append(result.MaterialBegins, v.HostCalls.MaterialBegin)
	}
	entries, err := os.ReadDir(filepath.Join(a.Dir, "temp", "plugin-material-spool"))
	if err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatal("completed Add retained owned spools", len(entries))
	}
	return result
}
func ownedMaterialAssertAttempt(t *testing.T, s ownedCommandLargeSource, result ownedMaterialWorkerSummary, index int, kind string, success bool) {
	t.Helper()
	a := result.Results[index]
	c := a.HostCalls
	g := result.Grants[index]
	if a.Generated == nil || a.Generated.Kind != s.Payload.ID || a.Generated.Length != s.Payload.Bytes || a.Generated.SHA256 != s.Payload.SHA256 {
		t.Fatal("real worker bytes differ from source input")
	}
	if c.Total != 2 || c.Begin != 1 || result.MaterialBegins[index] != 1 || c.Submit != 1 || c.Append != 0 || c.AppendPayloadBytes != 0 || c.Abort != 0 || c.Invoke != 0 || c.Other != 0 || c.MaxInputJSONBytes <= 0 || c.MaxInputJSONBytes > 128<<10 || c.InputJSONBytes >= 128<<10 {
		t.Fatal("actual material/control callback separation differs", c)
	}
	cap := plugins.QBittorrentAddCapability
	if kind == "transmission" {
		cap = plugins.TransmissionAddCapability
	}
	if g == nil || g.Contract != plugins.MaterialContract || g.Capability != cap || g.Direction != string(plugins.MaterialToHost) || g.Kind != "bytes" || g.Total != int64(s.Payload.Bytes) || g.SHA256 != s.Payload.SHA256 || g.ChunkBytes < 1 || g.ChunkBytes > plugins.MaterialFrameBytes {
		t.Fatal("actual fixed upload grant differs", g)
	}
	if !success {
		if a.OK || a.ErrorCode != "host_operation_failed" || len(a.Result) != 0 || c.Succeeded != 1 || c.Failed != 1 {
			t.Fatal("selected failure lost unknown-effect error", a.ErrorCode)
		}
		return
	}
	if !a.OK || c.Succeeded != 2 || c.Failed != 0 {
		t.Fatal("actual Add failed", a.ErrorCode)
	}
	if kind == "qbittorrent" {
		var original struct {
			Type  string
			Items []json.RawMessage
		}
		if json.Unmarshal(s.value(t, "s03_qb_bytes"), &original) != nil || original.Type != "tuple" || len(original.Items) != 2 {
			t.Fatal("original tuple missing")
		}
		var expected struct {
			Success bool     `json:"success"`
			IDs     []string `json:"ids"`
		}
		if json.Unmarshal(original.Items[0], &expected.Success) != nil || json.Unmarshal(original.Items[1], &expected.IDs) != nil {
			t.Fatal("original tuple fields missing")
		}
		ownedCommandAssertQB(t, a, expected.Success, expected.IDs)
	} else {
		var got, want map[string]any
		d := json.NewDecoder(bytes.NewReader(a.Result))
		d.UseNumber()
		e := json.NewDecoder(bytes.NewReader(s.value(t, "s03_tr_bytes")))
		e.UseNumber()
		if d.Decode(&got) != nil || e.Decode(&want) != nil || got["id"] != json.Number("901") || a.ResultKind != "transmission_native_json_not_python_torrent" || a.SourceTruthy != nil {
			t.Fatal("fixed owned native id or result envelope differs")
		}
		delete(got, "id") // This sole field is owned protocol support, not source expected.
		if !reflect.DeepEqual(got, want) {
			t.Fatal("remaining native fields differ from original recording reply")
		}
	}
}

func TestSharedDownloaderMaterialOriginalLargeWorkerRecoveryAndCold(t *testing.T) {
	source := ownedCommandLargeOracle(t)
	peers := newOwnedMaterialNativePeers(t, source)
	a, cookie := ownedCommandWorkerFixture(t, &ownedCommandPeers{qb: peers.qb, tr: peers.tr})
	qb := ownedCommandSourceOperation(t, source, "qbittorrent")
	tr := ownedCommandSourceOperation(t, source, "transmission")
	first := ownedMaterialWorkerQuery(t, a, cookie, false, qb, tr)
	if !first.OK || first.HadPrevious || first.Invocation != 1 {
		for _, attempt := range first.Results {
			t.Logf("owned operation=%s/%s sdk_ok=%v error_code=%s callbacks=%d succeeded=%d failed=%d", attempt.Kind, attempt.Op, attempt.OK, attempt.ErrorCode, attempt.HostCalls.Total, attempt.HostCalls.Succeeded, attempt.HostCalls.Failed)
		}
		t.Fatal("fresh actual large SDK chain failed")
	}
	ownedMaterialAssertAttempt(t, source, first, 0, "qbittorrent", true)
	ownedMaterialAssertAttempt(t, source, first, 1, "transmission", true)
	observed := peers.snapshot()
	if observed.Requests != 6 || observed.QB != 1 || observed.TR != 1 || observed.Unexpected != 0 {
		t.Fatal("first actual native dispatch counts", observed)
	}
	peers.mu.Lock()
	peers.failTR = true
	peers.mu.Unlock()
	recovered := ownedMaterialWorkerQuery(t, a, cookie, true, tr, qb)
	ownedCommandWorkerWarm(t, first.ownedCommandWorkerResult, recovered.ownedCommandWorkerResult)
	ownedCommandWorkerProbe(t, recovered.ownedCommandWorkerResult, "transmission", "add", "upload_material_begin")
	if recovered.OK || recovered.Failed != 1 || recovered.Succeeded != 1 {
		t.Fatal("failed Add and next distinct recovery lost")
	}
	ownedMaterialAssertAttempt(t, source, recovered, 0, "transmission", false)
	ownedMaterialAssertAttempt(t, source, recovered, 1, "qbittorrent", true)
	after := peers.snapshot()
	if after.Requests-observed.Requests != 6 || after.QB != 2 || after.TR != 2 || after.Failed != 1 || after.Unexpected != 0 {
		t.Fatal("selected failure replayed or stale probe dispatched", after)
	}
	installation, err := a.pluginStore.Installation(context.Background(), ownedCommandWorkerID)
	if err != nil || !installation.Installed {
		t.Fatal("missing installed artifact", err)
	}
	saved := a.Settings().Downloaders
	dir := a.Dir
	if err = a.Close(); err != nil {
		t.Fatal(err)
	}
	if peers.snapshot() != after {
		t.Fatal("close replayed selected Add")
	}
	cold, err := New(Options{DataDir: dir})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = cold.Close() })
	if err = cold.initializeOriginalPlugins(context.Background()); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(saved, cold.Settings().Downloaders) {
		t.Fatal("cold configuration changed")
	}
	retained, err := cold.pluginStore.Installation(context.Background(), ownedCommandWorkerID)
	if err != nil || !retained.Installed || retained.Generation != installation.Generation || retained.Version != installation.Version {
		t.Fatal("cold artifact identity changed")
	}
	if peers.snapshot() != after {
		t.Fatal("cold initialization replayed Add")
	}
	login := callTest(t, cold.Handler(), "POST", "/api/auth/login", `{"username":"admin","password":"a-strong-test-password"}`, nil, "")
	var coldCookie *http.Cookie
	for _, c := range login.Result().Cookies() {
		if c.Name == "lm_session" {
			coldCookie = c
		}
	}
	if login.Code != 200 || coldCookie == nil {
		t.Fatal("cold normal login failed")
	}
	reopened := ownedMaterialWorkerQuery(t, cold, coldCookie, true, tr)
	ownedMaterialAssertAttempt(t, source, reopened, 0, "transmission", true)
	if !reopened.OK || reopened.PID == first.PID || reopened.Invocation != 1 || reopened.HadPrevious || reopened.InitCount != first.InitCount || reopened.PreviousProbe == nil || reopened.PreviousProbe.Available || reopened.PreviousProbe.CallbackAttempts != 0 {
		t.Fatal("cold fresh real worker state differs")
	}
	final := peers.snapshot()
	if final.Requests-after.Requests != 3 || final.QB != 2 || final.TR != 3 || final.Failed != 1 || final.Unexpected != 0 || final.QBBytes != int64(source.Payload.Bytes) || final.TRBytes != int64(source.Payload.Bytes) || final.QBSHA != source.Payload.SHA256 || final.TRSHA != source.Payload.SHA256 {
		t.Fatal("final native material observations", final)
	}
}
